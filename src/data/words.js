/**
 * Diziyi Fisher-Yates algoritmasıyla tarafsız şekilde karıştırır.
 */
function shuffleArray(arr, rng = Math.random) {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const rand = typeof rng === 'function' ? rng() : Math.random();
    const j = Math.floor(rand * (i + 1));
    const temp = copy[i];
    copy[i] = copy[j];
    copy[j] = temp;
  }
  return copy;
}

/**
 * Deste durumunu sıfırlar (Yeni oyun başlatıldığında çağrılabilir).
 */
export function resetWordDeck() {
  deckState.easy = [];
  deckState.medium = [];
  deckState.hard = [];
  deckState.mixed = [];
}

/**
 * Belirtilen zorluk derecesine göre desteden kelime seçer.
 * Deste tükenene kadar hiçbir kelime tekrar etmez.
 * Deste bittiğinde havuz yeniden baştan karıştırılır.
 * Tohumlu rastgele üretici (PRNG) verildiğinde deterministic seçim yapar.
 * @param {'easy'|'medium'|'hard'|'mixed'} difficulty 
 * @param {string} lastWord 
 * @param {Function} [rng=Math.random]
 * @returns {string}
 */
export function getRandomWord(difficulty = 'easy', lastWord = '', rng = Math.random) {
  const key = words[difficulty] ? difficulty : (difficulty === 'mixed' ? 'mixed' : 'easy');
  const basePool = key === 'mixed'
    ? [...words.easy, ...words.medium, ...words.hard]
    : (words[key] || words.easy);

  // 1. Tohumlu (PRNG) Çok Oyunculu Durumu: İki oyuncunun tam senkron kelimeler alması için
  const isCustomRng = typeof rng === 'function' && rng !== Math.random;
  if (isCustomRng) {
    let attempts = 0;
    let chosen = '';
    while (attempts < 10) {
      const idx = Math.floor(rng() * basePool.length);
      chosen = basePool[idx] || basePool[0];
      if (chosen !== lastWord) break;
      attempts++;
    }
    return chosen || basePool[0] || 'kelime';
  }

  // 2. Normal Tek Kişilik Mod: Karıştırılmış Deste (Hiçbir kelime bitmeden tekrar etmez)
  if (!deckState[key] || deckState[key].length === 0) {
    deckState[key] = shuffleArray(basePool, rng);
  }

  let chosenWord = deckState[key].pop();

  if (chosenWord === lastWord && deckState[key].length > 0) {
    const alternative = deckState[key].pop();
    deckState[key].push(chosenWord);
    chosenWord = alternative;
  }

  return chosenWord || basePool[0] || 'kelime';
}

export default words;
